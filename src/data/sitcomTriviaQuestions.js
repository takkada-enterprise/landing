// Utility function to get a randomized shuffled deck of all 100 questions + shuffled options for each game run
export function getShuffledQuestions() {
  const deck = SITCOM_TRIVIA_QUESTIONS.map((q) => {
    const correctAnswerText = q.options[q.correctIndex];
    const shuffledOptions = [...q.options];
    for (let i = shuffledOptions.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [shuffledOptions[i], shuffledOptions[j]] = [shuffledOptions[j], shuffledOptions[i]];
    }
    const newCorrectIndex = shuffledOptions.indexOf(correctAnswerText);
    return {
      ...q,
      options: shuffledOptions,
      correctIndex: newCorrectIndex,
    };
  });

  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck;
}
